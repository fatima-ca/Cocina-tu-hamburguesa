CREATE TABLE public.usuarios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre text NOT NULL,
    edad integer NOT NULL CHECK (edad >= 0),
    creado_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.partidas (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    usuario_id bigint NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    iniciada_en timestamptz NOT NULL DEFAULT now(),
    terminada_en timestamptz,
    CONSTRAINT partidas_fechas_validas
        CHECK (terminada_en IS NULL OR terminada_en >= iniciada_en)
);

CREATE TABLE public.clics_receta (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partida_id uuid NOT NULL REFERENCES public.partidas(id) ON DELETE CASCADE,
    receta text NOT NULL,
    clicado_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.clics_detectar_error (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partida_id uuid NOT NULL REFERENCES public.partidas(id) ON DELETE CASCADE,
    clicado_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.confirmaciones_ensamblaje (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partida_id uuid NOT NULL REFERENCES public.partidas(id) ON DELETE CASCADE,
    confirmado_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.ingredientes_seleccionados_confirmacion (
    confirmacion_id bigint NOT NULL
        REFERENCES public.confirmaciones_ensamblaje(id) ON DELETE CASCADE,
    ingrediente text NOT NULL,
    PRIMARY KEY (confirmacion_id, ingrediente)
);

CREATE TABLE public.ingredientes_finales_confirmacion (
    confirmacion_id bigint NOT NULL
        REFERENCES public.confirmaciones_ensamblaje(id) ON DELETE CASCADE,
    posicion smallint NOT NULL CHECK (posicion > 0),
    ingrediente text NOT NULL,
    PRIMARY KEY (confirmacion_id, posicion),
    UNIQUE (confirmacion_id, ingrediente)
);

COMMENT ON COLUMN public.ingredientes_finales_confirmacion.posicion IS
    'Orden de los ingredientes de abajo hacia arriba en el ensamblaje.';

CREATE INDEX clics_receta_partida_id_idx
    ON public.clics_receta (partida_id);

CREATE INDEX clics_detectar_error_partida_id_idx
    ON public.clics_detectar_error (partida_id);

CREATE INDEX confirmaciones_ensamblaje_partida_id_idx
    ON public.confirmaciones_ensamblaje (partida_id);
